@dask.delayed
def read_voltage_traces_from_files_pandas(prefix, fnames, meta=None):
    """Reads a list of **multiple** voltage trace files and parses it to a single pandas dataframe.

    The delayed version of this method is used to construct a dask dataframe containing the voltage traces
    in :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_by_filenames`.
    Each singular file is read using :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_from_file`.

    Args:
        prefix (str): Path to the directory containing the simulation results.
        fnames (list): List of filenames pointing to voltage trace files.

    Returns:
        pandas.DataFrame: A pandas dataframe containing the voltage traces.

    See also:
        :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_by_filenames`.
    """
    dfs = [read_voltage_traces_from_file(prefix, fname, meta=meta) for fname in fnames]
    return pd.concat(dfs, axis=0)


def read_voltage_traces_from_file(prefix, fname, meta=None):
    """Reads a **single** voltage traces file as generated by the simrun package.

    Infers the data format of the voltage traces file from the file extension (either ``.csv`` or ``.npz``).
    Reads them in and parses it to a pandas datafram, containing the original path and simulation trial as an index.

    Example:

        >>> simrun_result_fn = 'path/to/sim_result/vm_all_traces.csv'
        >>> with open(simrun_result_fn, 'r') as file: print(file.read())
        # This is an example for a .csv file (so not .npz)
        t	    Vm run 00	    Vm run 01
        100.0	-61.4607218758	-55.1366909604
        100.025	-61.4665809176	-55.1294343391
        100.05	-61.4735021526	-55.1223216173
        ...
        >>> read_voltage_traces_from_file(prefix="path/to/sim_result", v_fn)
        sim_trial_index             100.0           100.025         ...
        path/to/sim_result/000000   -61.4607218758 -61.4665809176   ...
        path/to/sim_result/000001   -55.1366909604 -55.1294343391   ...
        ...

    Important:
        The simulation trial index is inferred from the filename of the voltage traces file.
        Ideally, this path should contain a unique identifier, containing e.g. the date,
        seed and/or the PID of the simulation run.

    Args:
        prefix (str): Path to the directory containing the simulation results.
        fname (str): Filename pointing to a voltage trace file. The file can be in either ``.csv`` or ``.npz`` format.

    Returns:
        pd.DataFrame: A pandas dataframe containing the voltage traces.

    See also:
        :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_from_csv` and
        :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_from_npz`
    """
    logger.debug(f"Reading voltage trace file: {fname}")
    try:
        if fname.endswith(".csv"): return read_voltage_traces_from_csv(prefix, fname)
        if fname.endswith(".npz"): return read_voltage_traces_from_npz(prefix, fname)
    except Exception as e:
        logger.error(e)
        # Return empty DataFrame with same structure as meta
        # These will simply be ignored by upstream dd.from_delayed()
        empty_df = pd.DataFrame(columns=meta.columns).astype(meta.dtypes)
        return empty_df


read_voltage_traces_from_file_delayed = dask.delayed(read_voltage_traces_from_file)


def _get_sim_trial_index_from_simresult_dir(prefix, dir_path, check_n_traces=None):

    syn_files = [os.path.basename(f) for f in glob.glob(os.path.join(prefix, dir_path, "*synapses*"))]
    cell_files = [os.path.basename(f) for f in glob.glob(os.path.join(prefix, dir_path, "*presynaptic_cells*"))]

    if check_n_traces is not None:
        if not len(syn_files) == check_n_traces == len(cell_files): raise ValueError(
            "Amount of runs does not match: {} synapse activation files, {} voltage traces, and {} cell activation files".format(
                len(syn_files), check_n_traces, len(cell_files)))
    
    # Special case: if the simulations runs are not consecutive. Fetch the run id form the synapse activation files instead
    run_ids = sorted(int(f.split("_")[1][3:]) for f in syn_files)
    index = [
        str(os.path.join(dir_path, str(run_id).zfill(6)))
        for run_id in run_ids
    ] 
    return index


def read_voltage_traces_from_csv(prefix, fname):
    """Reads a single :ref:`voltage_traces_csv_format` file as generated by the simrun package.
    
    Attention:
        This function assumes that the data in :paramref:prefix: is complete, e.g. no missing files.
        It infers the simulation trial index from the filename of the synapse activation files.
        :py:fun:`_check_if_results_are_corrupted` checks if this is the case.
        This is automatically done in the :py:mod:`data_base.db_initializers.load_simrun_general` module.
        
    Args:
        prefix (str): Path to the directory containing the simulation results.
        fname (str): Filename pointing to a voltage trace file. The file is expected to be in ``.csv`` format.
        
    """
    full_fname = os.path.join(prefix, fname)

    df = pd.read_csv(
        full_fname, 
        sep=r"\t", # use tab as sep (not whitespace, the columntitles have spaces in them...)
        engine="python", # use python engine to handle whitespace
        dtype=np.float64, # ensure all data is read as float64
        )
    t = df.iloc[:, 0].to_numpy()        # first column = time
    data = df.iloc[:, 1:].to_numpy().T  # transpose: rows=traces, columns=time
    n_traces = data.shape[0]

    # special case: if only one row is contained in data, this has to be a column vector
    data = np.atleast_2d(data)

    # Construct the sim trial index for these voltage traces
    dir_path = os.path.dirname(fname)
    index = _get_sim_trial_index_from_simresult_dir(prefix, dir_path, check_n_traces=n_traces)
    
    result = pd.DataFrame(
        data, 
        columns=t, 
        index=index
        )
    result.index.name = "sim_trial_index"
    return result


