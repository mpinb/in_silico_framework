def read_voltage_traces_from_npz(prefix, fname):
    """Reads a single :ref:`voltage_traces_npz_format` file as generated by the simrun package.

    Args:
        prefix (str): Path to the directory containing the simulation results.
        fname (str): Filename pointing to a voltage trace file. The file is expected to be in ``.npz`` format.

    See also:
        :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_from_file`
    """
    logger.warning(
        "You are loading voltage traces from npz files. This only works, if you are using a fixed stepsize of 0.025 ms"
    )
    data = np.load(os.path.join(prefix, fname))["arr_0"]
    data = np.transpose(data)
    vt = data[1:, :]
    t = np.array([0.025 * n for n in range(data.shape[1])])
    sim_trial_index_base = os.path.dirname(
        fname
    )  # os.path.dirname(os.path.relpath(prefix, fname))
    index = [
        str(os.path.join(sim_trial_index_base, str(index).zfill(6)))
        for index in range(len(vt))
    ]  ##this will be the sim_trial_index

    df = pd.DataFrame(vt, columns=t)
    df["sim_trial_index"] = index
    df.set_index("sim_trial_index", inplace=True)

    return df


def read_voltage_traces_by_filenames(prefix, fnames, divisions=None, repartition=None):
    """Reads a list of **multiple** voltage trace files and parses it to a dask dataframe.

    Also sets the database key ``sim_trial_index`` to contain the paths of the simulation trials.
    This is the default way of constructing a dask dataframe containing the voltage traces.

    Args:
        prefix (str): Path to the directory containing the simulation results.
        fnames (list): list of filenames pointing to voltage trace files
        divisions (list, optional): list of divisions for the dask dataframe. Default is ``None``, letting Dask handle it.
        repartition (bool|int): 
            If ``int``, the voltage trace dataframes will be partitioned to be of this length (approximately).
            If ``True``, the votlage trace dataframes will be partitioned to be of a default length: :py:attr:`~data_base.db_initializers.load_simrun_general.DEFAULT_VT_PARTITION_SIZE`
            If ``False``, the voltage trace dataframe will not be repartitioned, and the dask dataframe will be one ``.csv`` file per partition.

    Returns:
        dask.DataFrame: A dask dataframe containing the voltage traces.

    See also:
        :py:meth:`~data_base.db_initializers.load_simrun_general.read_voltage_traces_from_file`
        is used to read in each single voltage trace file. Consult this method for more information on how the data format
        is parsed.
    """
    assert repartition is not None
    fnames = sorted(fnames)
    meta = read_voltage_traces_from_file(prefix, fnames[0]).head(0)

    if repartition is not False:
        if divisions is not None:
            n_chunks = len(divisions) - 1
        else:
            if repartition == True: vt_partition_size = DEFAULT_VT_PARTITION_SIZE
            elif isinstance(repartition, int): vt_partition_size = repartition
            filelist = [os.path.join(prefix, fn) for fn in fnames]
            n_chunks = _estimate_n_chunks(filelist, partition_size=vt_partition_size)

        chunked_fnames = chunkIt(fnames, n_chunks)
        delayeds = [
            read_voltage_traces_from_files_pandas(prefix, fnames_chunk)
            for fnames_chunk in chunked_fnames
        ]
    else:
        # One file read per worker
        delayeds = [
            read_voltage_traces_from_file_delayed(prefix, fname, meta=meta) for fname in fnames
        ]
    
    if divisions is not None:
        assert len(divisions) - 1 == len(delayeds), "Expected n_delayeds = n_divisions + 1, but I have {} divisions and {} delayeds".format(
            len(divisions), len(delayeds)
        )

    ddf = dd.from_delayed(delayeds, meta=meta, divisions=divisions)
    return ddf

    
    
def load_dendritic_voltage_traces(
    db, 
    filelist,
    recsite_labels, 
    repartition=None,
    divisions=None,
    ):
    """Load the voltage traces from dendritic recording sites.

    This functions reads in all dendritic voltage trace files corresponding
    to each recsite label in :paramref:`suffix_key_dict`.
    Dendritic voltage traces recorded with recsites of the same label are aggregated in a single file.

    Attention:
        While voltage traces are combined depending on their recsite label, this does not mean
        that these voltage traces belong to the same simulation. Only the ``sim_trial_index`` is
        a reliable readout to check which simulation runs used the same parameters.

    Args:
        db (:py:class:`~data_base.DataBase`):
            The target database that should contain the parsed simulation results.
        suffix_key_dict (dict):
            Dictionary containing the suffixes of the dendritic voltage trace files.
            The keys are the labels of the recording sites, and the values are the suffixes of the dendritic voltage trace files.
        repartition (bool):
            If True, the dask dataframe is repartitioned to 5000 partitions (only if it contains over :math:`10000` entries).

    Returns:
        Dict[str, :py:class:`dask.dataframe.DataFrame`]: 
            Dictionary mapping each recsite label to a dask dataframe containing the associated voltage traces.

    """
    assert repartition is not None
    filelist = unique(filelist)
    df = pd.DataFrame({'filepath': filelist, 'label': recsite_labels})
    recsite_label_filelist_dict = df.groupby('label')['filepath'].apply(list).to_dict()
    recsite_dendvt_dict = {}
    for recsite_label, filelist in recsite_label_filelist_dict.items():
        ddf = read_voltage_traces_by_filenames(
            db["simresult_path"], filelist, divisions=divisions, repartition=repartition
        )
        recsite_dendvt_dict[recsite_label] = ddf
    return recsite_dendvt_dict


def _read_n_vtraces(fname):
    """Read the amount of voltage traces in a voltage trace file.
    
    Args:
        fname (str): Filename of a voltage trace file.
        
    Raises:
        NotImplementedError: If the voltage trace file is in .npz format.
        
    Returns:
        int: Amount of voltage traces in :paramref:`fname`.
    """
    if fname.endswith('.npz'):
        raise NotImplementedError("Don't know how to count the amount of traces for the .npz format: {}".format(fname))
    cols = pd.read_csv(
            fname, 
            nrows=0, 
            sep=r'\t', 
            engine="python", # use python engine to handle whitespace
            dtype=np.float64 # ensure all data is read as float64
        ).columns
    return len(cols) - 1  # one column is time, not voltage


def _estimate_average_vt_length(fnames, sample_size=1):
    """Estimate the length of all voltage traces in :paramref:`fnames`
    
    Reads the headers of :paramref:`sample_size` random files in :paramref:`fnames` to fetch
    how many voltage traces they contain. Returns the average amount.
    
    Args:
        fnames (List[str]): List of voltage trace filenames.
        sample_size (int): Amount of voltage traces headers to read in order to infer their length.
            Set to ``1`` if you expect all votlage trace filenames in :paramref:`fnames` to be of equal length.

    Returns:
        int: Estimated average length of all voltage trace files.
    """
    vt_lengths = [_read_n_vtraces(f) for f in np.random.choice(fnames, size=sample_size)]
    return int(np.mean(vt_lengths))

    
def _estimate_n_chunks(filelist, estimate_sample_size=1, partition_size=None):
    """Estimate how to divide filenames in chunks so that each chunk is approximately the target dask partition size.
    
    This function relies on the global config variable 
    :py:attr:`~data_base.db_initializers.load_simrun_general.config.DASK_TARGET_PARTITION_SIZE`

    Args:
        filelist (List[str]): List of voltage trace filenames
        estimate_sample_size (int, optional): 
            Amount of files to sample in order to estimate their length. Set to ``1`` if you expect all files to be of equal length.

    Returns:
        int: 
            The amount of chunks to divide the filelist in such that each chunk will yield a dataframe of approximate size 
            :py:attr:`~data_base.db_initializers.load_simrun_general.config.DASK_TARGET_PARTITION_SIZE`
    """
    assert partition_size is not None, "Please pass a target partition size."
    est_vt_length = _estimate_average_vt_length(filelist, sample_size=estimate_sample_size)
    n_files_per_chunk = partition_size // est_vt_length
    n_chunks = len(filelist) // n_files_per_chunk
    return n_chunks